/**
 * 将富文本 HTML 源码格式化为便于逐行对比的形式。
 *
 * 富文本（tiptap）导出的 HTML 通常是不含换行的单行字符串（如
 * `<p>a</p><p>b</p>`），直接进行逐行 diff 时整段会被判为「一行变更」，可读性极差。
 * 这里仅在「紧邻的两个标签之间」（`></`）插入换行，把块级标签拆到独立行。
 * 该转换「只插入、不删改」任何字符：标签内文本与标签间空白都原样保留，内容不丢失。
 * 注意它不保证可逆——若输入本身已含换行（如 `<pre><code>` 多行代码块），插入的换行
 * 会与原有换行混在一起，无法仅靠去掉换行还原。这只影响展示形态，不影响对比正确性：
 * 对比两侧均经同一函数处理，差异是对称的，相同内容不会被造出「伪差异」。
 */
export function formatHtmlForDiff(html: string): string {
  if (!html) return ''
  return html.replace(/></g, '>\n<')
}
